// for more details.
//
// The CPU itself (wf68k30L_*.vhd, WF68K30L IP core, (C) Wolfgang Foerster,
// CERN OHL 1.2, with the rigsdram audit fixes and the FalconFPGA fixes listed
// in BUILD_REPORT.md, F55..F58).
//
// ---------------------------------------------------------------------------
// Structure
//
//   clk_cpu / clk_cpu_n (the 030; clk_cpu_n = clk_cpu at 180 degrees from
//     the same PLL, clocks the core's falling-edge registers, CLK_N_EXT = 1)
//     WF68K30L_TOP, CPU reset counter.
//   clk_32 domain (the ST chipset). clk_cpu is phase-locked to clk_32 (same
//   VCO, every clk_cpu/clk_cpu_n edge is a clk_32 rising edge), so the 030's
//   outputs and the bridge registers are exchanged directly as timed
//   related-clock paths, like a TerribleFire board running its 68000 bus
//   synchronously (F58; before, both directions went through 2-flop
//   synchronisers and an ST access took ~1.6 us, now ~0.9 us at 16 MHz):
//     front end: on the first clk_32 edge that sees ASn low, latch address,
//       SIZE, RW, FC and write data and toggle req_t. c_open drops on the
//       clk_32 edge that sees ASn high, which gates every termination off
//       before the 030's next falling-edge sample.
//     one 68000 bus cycle is run on the ST bus with the fx68k phase timing on
//     mhz8_en1/en2 (DTACK/VPA+E/BERR termination, arbitration BR/BG/BGACK, E
//     and VMA). DSACKn="01" (16-bit port) is given on the en2 edge where a
//     68000 samples DTACK (S4) with an 8 MHz clk_cpu (CPU_DIV 4), one phase
//     later (S4 -> S6 en1) with the 16 MHz clk_cpu used on the board
//     (CPU_DIV 2); the read word is latched at S6 en2 (the 68000's latch
//     edge), before the 030 latches it one clk_cpu after its DSACK sample.
//     VPA/E-cycle, autovector (AVECn) and BERR terminations are given at S6
//     en2 together with the request tag.
//
// Bus sizing: the 030 does its own dynamic bus sizing. Every ST cycle is
// answered as a 16-bit port (DSACKn = "01"): even byte on D31:24, odd byte on
// D23:16, words on D31:16. A long or a misaligned word becomes several ST
// cycles, generated by the 030 itself.
// Addresses: A23:1 only (A31:24 ignored), so the 030 sees the ST's 24-bit
// aliasing like a real ST.
// CPU space (FC=7): A19:16=F is an interrupt acknowledge and runs a real ST
// IACK cycle (MFP vector via DTACK, or VPA -> AVECn autovector). Any other
// CPU-space cycle (breakpoint, coprocessor, MMU) gets BERR at once without an
// ST cycle.
// ---------------------------------------------------------------------------

`default_nettype none

module cpu030_st_bridge #(
    parameter integer SYNC_STAGES = 2,    // unused since F58 (no request synchroniser), kept for compatibility
    parameter integer RESET_HOLD  = 128,  // RESET_INn+HALT_INn low, clk_cpu cycles (>=16)
    parameter integer CPU_DIV     = 4     // clk_32 / clk_cpu: 4 = 8 MHz, 2 = 16 MHz (both phase-locked)
) (
    input  wire        clk,         // clk_32 (ST chipset clock)
    input  wire        clk_cpu,     // 030 clock (16 MHz on the board, related to clk_32)
    input  wire        clk_cpu_n,   // 180 degree copy of clk_cpu (PLL): the 030's falling-edge registers
    input  wire        extReset,    // ST reset (clk_32 domain)
    input  wire        pwrUp,       // power-up reset (clk_32 domain)
    input  wire        enPhi1,      // mhz8_en1
    input  wire        enPhi2,      // mhz8_en2

    output wire        eRWn,
    output wire        ASn,
    output wire        ASEn,        // F61: address phase (S0) of a cycle, before ASn (TOS flash read start)
    output wire        LDSn,
    output wire        UDSn,
    output reg         E,
    output wire        VMAn,
    output wire        FC0,
    output wire        FC1,
    output wire        FC2,
    output reg         BGn,
    output wire        oRESETn,
    output wire        oHALTEDn,
    input  wire        DTACKn,
    input  wire        VPAn,
    input  wire        BERRn,
    input  wire        HALTn,       // unused (tied high in atarist.v)
    input  wire        BRn,
    input  wire        BGACKn,
    input  wire        IPL0n,
    input  wire        IPL1n,
    input  wire        IPL2n,
    input  wire [15:0] iEdb,
    output wire [15:0] oEdb,
    output wire [23:1] eab,
    output reg         rom_fetch,  // latched first ROM-window cycle, cleared by reset
    // FalconFPGA DIAG build (diag_overlay.v), observation only
    output wire        dbg_run,    // cpu_rst_n: 030 out of reset (clk_cpu domain)
    output wire        dbg_req,    // req_now: toggles once per 030 AS cycle (clk_32)
    output wire        dbg_dsack,  // s_dsack (clk_32)
    output wire        dbg_berr,   // s_berr (clk_32)
    // FalconFPGA DIAG diag030b/c, observation only (mixed clk_32/clk_cpu,
    // read through 2-FF syncs in the overlay; values are slow or frozen):
    // [167:128] {got, FC2:0, RW, SIZE1:0, bad_space, A31:0 at first BERR} (clk_32)
    // [127:96]  row c: A31:0 of the last bus cycle STARTED by the 030 (clk_cpu)
    // [95:64]   row d: last-start info + termination + CPU pins (clk_cpu)
    // [63:32]   row e: bridge 68000-side state machine (clk_32)
    // [31:0]    row f: {start count 7:0, live last program fetch A23:0} (clk_cpu)
    output wire [167:0] dbg_trace
`ifdef TTRAM
    ,
    // FalconFPGA TTRAM (docs/TTRAM_DESIGN.md): 030-side TT-RAM at $01000000
    input  wire        tt_en,       // switch: 1 = TT-RAM on, 0 = plain ST (A31:24 ignored, 24-bit wrap)
    output reg         tt_req = 1'b0,
    output reg         tt_we  = 1'b0,
    output reg  [21:0] tt_la  = 22'd0,
    output reg  [3:0]  tt_be  = 4'd0,
    output reg  [31:0] tt_wdata = 32'd0,
    input  wire        tt_ack,
    input  wire [31:0] tt_rdata
`endif
);

    // =====================================================================
    // clk_cpu domain: CPU reset and the 030 core
    // =====================================================================
    // RESET_INn and HALT_INn are held low together for RESET_HOLD clk_cpu
    // cycles after the ST reset (or power-up) ends. RESET_OUT (RESET
    // instruction) is not fed back into the CPU; it goes to the ST as
    // oRESETn like fx68k's.
    localparam [7:0] RHOLD = RESET_HOLD;
    (* syn_preserve = 1 *) reg [1:0] rst_sync = 2'b11;
    reg [7:0]  rst_cnt   = 8'd0;
    reg        cpu_rst_n = 1'b0;
    wire       st_rst    = extReset | pwrUp;

    always @(posedge clk_cpu) begin
        rst_sync <= {rst_sync[0], st_rst};
        if (rst_sync[1]) begin
            rst_cnt   <= 8'd0;
            cpu_rst_n <= 1'b0;
        end else if (rst_cnt != RHOLD) begin
            rst_cnt   <= rst_cnt + 8'd1;
            cpu_rst_n <= 1'b0;
        end else begin
            cpu_rst_n <= 1'b1;
        end
    end

    wire [31:0] cpu_adr, cpu_dout;
    wire [31:0] cpu_din;
    wire [1:0]  cpu_size, cpu_dsackn;
    wire [2:0]  cpu_fc;
    wire        cpu_asn, cpu_rwn, cpu_rmcn, cpu_dsn;
    wire        cpu_reset_out, cpu_halt_outn;
    wire        cpu_berrn, cpu_avecn;
    wire        cpu_ipendn, cpu_statusn;
    wire        cpu_mmu_on;            // [F66] TC.E of the 030 (clk_cpu register)
    wire [104:0] cpu_dbg_exc;          // FalconFPGA DIAG {taken, vector, SR, PC, A5, BIW_0} (RTL only)
    // [IC] CIIN address decode, per bus cycle, as a 030 board drives it (MC68030UM 5.7.1: "interpreted
    // on a bus-cycle-by-bus-cycle basis"; the core latches it at the start of S4, or with STERM).
    // Decoded from the cycle the 030 is running (AS asserted, its own A31:0 and FC2:0):
    //   - every ST-side cycle (ROM, ST-RAM, I/O, all of A31:24 other than $01) and every CPU-space
    //     cycle (FC = 7): CIINn asserted (TF536 rule, CACHE_PLAN.md: the ST side is never cached);
    //   - the reserved 030-side fast-RAM range $01000000-$01FFFFFF (TT-RAM style, CACHE_PLAN.md):
    //     CIINn negated (cachable). Nothing is fitted there yet: those cycles still go to the ST bus
    //     like any other address (A31:24 are ignored on it), and no ST software runs code there.
    //   - no cycle of the 030 (AS negated, e.g. while the ST side owns the bus): CIINn asserted.
    // CIIN only stops the current cycle's data from being cached; it never disables the cache, and
    // entries already in it still hit (MC68030UM 6.1). CDISn is the only hardware disable.
    // CIINn is active low: asserted (0) = do not cache this cycle, negated (1) = cachable.
    (* syn_keep = 1 *) wire cpu_fast_sel;
    assign cpu_fast_sel = ~cpu_asn & (cpu_fc != 3'b111) & (cpu_adr[31:24] == 8'h01);
`ifdef TTRAM
    // TTRAM: cachable only while TT-RAM is switched on; switched off, $01xxxxxx wraps to the ST
    // side (24-bit) and must be cache-inhibited like any other ST cycle.
    wire cpu_cii_n = cpu_fast_sel & tt_en;
`else
    wire cpu_cii_n = cpu_fast_sel;      // negated only for the reserved fast-RAM range
`endif
`ifdef TT_RING
    wire [127:0] cpu_dbg_str;          // FalconFPGA DIAG STR
`endif
    wire [31:0] cpu_dbg_adr;           // FalconFPGA DIAG {ADR_LATCH, ADR_P, PC_L, ADR_L} 23:16   // FalconFPGA DIAG
    reg  [2:0]  ipl_r = 3'b111;

`ifdef WF030_NETLIST
    // gate-level simulation (sim/run_unit.sh): the netlist from
    // sim/wf030_syn.tcl is synthesised with CLK_N_EXT = 1 and has no generics
    WF68K30L_TOP i_wf68k30l (
`else
    WF68K30L_TOP #(
        .CLK_N_EXT ( 1             ),   // falling-edge registers on clk_cpu_n (global clock)
        .CACHES    ( 0             ),    // [IC] ignored: the 68030 I cache is always built; CIINn below decides
`ifdef WF030_FAST_HANDOFF
        .FAST_HANDOFF ( 1          )     // [F65] prefetch S5 rolls into the next prefetch S0
`else
        .FAST_HANDOFF ( 0          )     // [F65] IDLE -> START_CYCLE between prefetches
`endif
    ) i_wf68k30l (
`endif
        .CLK       ( clk_cpu       ),
        .CLK_N     ( clk_cpu_n     ),
        .ADR_OUT   ( cpu_adr       ),
        .DATA_IN   ( cpu_din       ),
        .DATA_OUT  ( cpu_dout      ),
        .DATA_EN   (               ),
        .BERRn     ( cpu_berrn     ),
        .RESET_INn ( cpu_rst_n     ),
        .RESET_OUT ( cpu_reset_out ),
        .HALT_INn  ( cpu_rst_n     ),
        .HALT_OUTn ( cpu_halt_outn ),
        .FC_OUT    ( cpu_fc        ),
        .AVECn     ( cpu_avecn     ),
        .IPLn      ( ipl_r         ),
        .IPENDn    ( cpu_ipendn    ),   // FalconFPGA DIAG (was open)
        .DSACKn    ( cpu_dsackn    ),
        .SIZE      ( cpu_size      ),
        .ASn       ( cpu_asn       ),
        .RWn       ( cpu_rwn       ),
        .RMCn      ( cpu_rmcn      ),
        .DSn       ( cpu_dsn       ),
        .ECSn      (               ),
        .OCSn      (               ),
        .DBENn     (               ),
        .BUS_EN    (               ),
        .STERMn    ( 1'b1          ),
        // [IC] 68030 cache pins. CIINn from the per-cycle address decode above (cpu_cii_n), never a
        // constant: ST-side cycles inhibited (TF536 rule, CACHE_PLAN.md §4), the reserved fast-RAM
        // range cachable. The cache is always built and enabled by CACR EI.
        .CIINn     ( cpu_cii_n     ),
        .MMU_ON    ( cpu_mmu_on    ),   // [F66] TC.E: pins sampled one clk_cpu after AS
        .CDISn     ( 1'b1          ),   // no hard cache-off (CIIN keeps ST-side code out of the cache)
        .CBACKn    ( 1'b1          ),   // no burst-capable memory
        .CBREQn    (               ),
        .CIOUTn    (               ),
`ifndef WF030_NETLIST
        .DBG_ADR   ( cpu_dbg_adr   ),   // FalconFPGA DIAG (RTL only)
`ifdef TT_RING
        .DBG_STR   ( cpu_dbg_str   ),   // FalconFPGA DIAG STR
`endif
        .DBG_EXC   ( cpu_dbg_exc   ),   // FalconFPGA DIAG (RTL only)
`endif
        .STATUSn   ( cpu_statusn   ),   // FalconFPGA DIAG (was open)
        .REFILLn   (               ),
        .BRn       ( 1'b1          ),   // arbitration is done on the ST side
        .BGn       (               ),
        .BGACKn    ( 1'b1          )
    );

`ifdef TTRAM
    // ---- FalconFPGA TTRAM front end (clk_32) ---------------------------------
    // With tt_en, the 030's own 32-bit address is decoded (FC != 7):
    //   A31:24 = $00, $FF : ST side, as before (24-bit bus, $FFxxxxxx = short I/O addressing)
    //   A31:24 = $01      : TT-RAM, 32-bit port (DSACK1:0 = 00), cachable (CIIN negated)
    //                       A23:0 >= TT_BYTES -> bus error
    //   $02..$7F data     : bus error (no ST wrap: EmuTOS sizes TT-RAM by BERR / mirror tests)
    //   $80..$FE, and program fetches with any A31:24 but $01: ST side, 24-bit wrap [T10/T10b]
    // With tt_en = 0 nothing here is used and A31:24 are ignored (plain ST, 24-bit wrap).
    localparam [24:0] TT_BYTES = 25'h1000000;   // 16 MB ($01000000-$01FFFFFF), 25'h0800000 = 8 MB
    // [T10] program-space cycles (FC = 2/6) with A31:24 other than $01 take the ST side (24-bit
    // wrap, as on a 68000): TOS 2.06 fills vectors 2..63 with $E010E2 + (vector << 24) (the bomb
    // handler reads the vector number back from the PC high byte), so the first exception through
    // one of them fetched $nnE010E2 -> BERR -> vector 2 = $02E010E2 -> BERR loop: the boot hung at
    // the first Pexec. Data cycles still bus-error, so TT-RAM sizing (EmuTOS reads up from
    // $01000000 until a BERR at $02000000) is unchanged.
    // [T10b] A31 = 1 ($80..$FF) always takes the ST side: the TOS 2.06 BIOS/XBIOS dispatcher ($E00D80)
    // marks indirect table entries with bit 31 and reads them with movea.l (a0),a0 at $80000472 etc.
    // Data BERR is kept only for $02..$7F (TT-RAM sizing, TT_RING $7E).
    wire cpu_pgm    = (cpu_fc[1:0] == 2'b10);
    wire cpu_tt_any = tt_en & ~cpu_asn & (cpu_fc != 3'b111) &
                      (cpu_adr[31:24] != 8'h00) & ~cpu_adr[31] &
                      ((cpu_adr[31:24] == 8'h01) | ~cpu_pgm);
    wire cpu_tt_ram = cpu_tt_any & (cpu_adr[31:24] == 8'h01) & ({1'b0, cpu_adr[23:0]} < TT_BYTES);
    // L1: the request goes to sdram.v straight from the 030 pins (A/SIZE/RW/data are valid with AS,
    // as for the ST front end), so sdram.v sees it on the first clk_32 edge with AS low.
    // L2: sdram.v acks a read 3 clk_32 before tt_dout is complete; t_dsack (one edge later) is
    // sampled by the 030 on a clk_cpu falling edge >= 1 clk_32 later and the data latched one clk_cpu
    // (2 clk_32) after that, i.e. on or after the edge where tt_dout is loaded + 1. cpu_din takes
    // tt_rdata (the sdram.v register) directly. Writes are posted: acked when sdram.v takes them.
    reg  t_open = 1'b0, t_dsack = 1'b0, t_berr = 1'b0, t_got = 1'b0;
    // [C5] TT5: no early read DSACK. A read is acked only once tt_dout is complete (3 edges after
    // tt_ack) and captured into t_rd, which is held until AS rises, so the data the 030 latches can
    // never be a register that sdram.v is still loading. DSACK/BERR then reach the 030 through
    // clk_cpu flops (async clear on AS), not straight from clk_32 regs.
    // Technique after TF536 by Stephen J. Leary (registered, AS-cleared terminations); own code.
    reg  [2:0]  t_rp = 3'd0;
    reg  [31:0] t_rd = 32'd0;
    // byte lanes of a 32-bit port (MC68030UM 7.2.1): from A1:0 up to A1:0+size-1, at most lane 3
    wire [2:0] tt_n  = (cpu_size == 2'b00) ? 3'd4 : {1'b0, cpu_size};
    wire [3:0] tt_lo = (4'b1111 >> cpu_adr[1:0]);                     // lanes >= A1:0 ([3] = lane 0)
    wire [3:0] tt_hi = ~(4'b1111 >> ({1'b0, cpu_adr[1:0]} + tt_n));    // lanes <  A1:0+n
    // TT1: L1 undone for timing (clk_cpu030 pins -> sdram.v start logic missed clk32): the request is
    // registered from the pins at the first clk_32 edge with AS low again (+1 clk_32 per TT cycle).
`ifdef TT_RING
    // ---- FalconFPGA DIAG TT_RING: last 32 030 bus cycles before the first BERR (clk_32) ----
    // A31:24 = $7E is a register port (32-bit, no wait): a write arms (clears and starts) the ring;
    // a read of $7E000000 + 16*i + 4*k returns entry i (0 = newest) word k: 0 addr, 1 data,
    // 2 {wp, i, armed, frozen, 0.., FC2:0, RW, SIZE1:0, TT, BERR}, 3 count of cycles since arm.
    // Every 030 cycle (TT and ST, not the port itself) is logged when it terminates; the first
    // BERR termination while armed is logged and freezes the ring. Observation only.
    reg t_open_ring = 1'b0;
    wire        cpu_ring = cpu_tt_any & (cpu_adr[31:24] == 8'h7E);
    reg  [31:0] g_adr [0:31];
    reg  [31:0] g_dat [0:31];
    reg  [7:0]  g_inf [0:31];
    reg  [4:0]  g_wp  = 5'd0;
    reg         g_arm = 1'b0, g_frz = 1'b0, g_lg = 1'b0;
    reg  [31:0] g_cnt = 32'd0;
    wire        g_term = ~cpu_asn & ((cpu_dsackn != 2'b11) | ~cpu_berrn | ~cpu_avecn);
    wire [4:0]  g_i   = g_wp - 5'd1 - cpu_adr[8:4];
    wire [31:0] g_rdat = (cpu_adr[3:2] == 2'd0) ? g_adr[g_i] :
                         (cpu_adr[3:2] == 2'd1) ? g_dat[g_i] :
                         (cpu_adr[3:2] == 2'd2) ? {3'd0, g_wp, 3'd0, cpu_adr[8:4], g_arm, g_frz, 6'd0, g_inf[g_i]} : g_cnt;
    always @(posedge clk) begin
        if (cpu_asn) g_lg <= 1'b0;
        if (!cpu_rst_n) begin
            g_arm <= 1'b0; g_frz <= 1'b0;
        end else if (!t_open & cpu_ring & ~cpu_rwn) begin
            g_arm <= 1'b1; g_frz <= 1'b0; g_wp <= 5'd0; g_cnt <= 32'd0; g_lg <= 1'b1;
        end else if (g_term & ~g_lg & ~cpu_ring & ~t_open_ring) begin
            g_lg <= 1'b1;
            if (g_arm & ~g_frz) begin
                g_adr[g_wp] <= cpu_adr;
                g_dat[g_wp] <= cpu_rwn ? cpu_din : cpu_dout;
                g_inf[g_wp] <= {cpu_fc, cpu_rwn, cpu_size, t_open, ~cpu_berrn};
                g_wp  <= g_wp + 5'd1;
                g_cnt <= g_cnt + 32'd1;
                if (~cpu_berrn) g_frz <= 1'b1;
            end
        end
    end
    // ---- FalconFPGA DIAG STR: decoder word stream + ISP ring (clk_cpu), 64 entries ----
    // An entry is logged on every clk_cpu with a queue event (Q_HIT, IC_TAKE, PF_DONE, Q_MISS) or an ISP change,
    // while armed (the same $7E000000 arm write, synchronised). Trigger: the first ISP write to $01xxxxxx with
    // ISP[1] = 0 (TTM1's SP is always 2 mod 4 in the suite) or a BERR; 40 more entries are logged, then frozen.
    // Read at $7E800000 + 16*i + 4*k, i = 0 newest: k0 {Q_HEAD,0}, k1 {word0, QF, QCNT, 0, clocks since previous entry (6), trig, frz},
    // k2 ISP, k3 {BIW_0 (current opcode), lookup F_ADR7:1, fill F_CUR7:2, IC_HIT, PF_DONE, F_CUR1}.
    reg  [31:0] d_w0 [0:63];
    reg  [31:0] d_w1 [0:63];
    reg  [31:0] d_w2 [0:63];
    reg  [31:0] d_w3 [0:63];
    reg  [5:0]  d_wp = 6'd0;
    reg  [1:0]  d_as = 2'b00;
    reg         d_trg = 1'b0, d_frz = 1'b0, d_a1 = 1'b0;
    reg  [5:0]  d_post = 6'd0;
    reg  [31:0] d_sp = 32'd0;
    reg  [5:0]  d_clk = 6'd0;           // clk_cpu cycles since the previous logged entry (saturates at 63)
    wire [31:0] d_isp = cpu_dbg_str[63:32];
    wire        d_ev = (cpu_dbg_str[79:76] != 4'd0) | (d_isp != d_sp);
    always @(posedge clk_cpu) begin
        d_as <= {d_as[0], g_arm};
        d_a1 <= d_as[1];
        d_sp <= d_isp;
        if (~(d_as[1] & ~d_frz & d_ev) & (d_clk != 6'd63)) d_clk <= d_clk + 6'd1;
        if (d_as[1] & ~d_a1) begin
            d_wp <= 6'd0; d_trg <= 1'b0; d_frz <= 1'b0; d_post <= 6'd0;
        end else if (d_as[1] & ~d_frz & d_ev) begin
            d_w0[d_wp] <= cpu_dbg_str[127:96];
            d_w1[d_wp] <= {cpu_dbg_str[95:72], d_clk, d_trg, d_frz};
            d_clk <= 6'd1;
            d_w2[d_wp] <= d_isp;
            d_w3[d_wp] <= cpu_dbg_str[31:0];
            d_wp <= d_wp + 6'd1;
            if (~d_trg & (((d_isp != d_sp) & (d_isp[31:24] == 8'h01) & ~d_isp[1]) | (~cpu_asn & ~cpu_berrn)))
                d_trg <= 1'b1;
            if (d_trg) begin
                d_post <= d_post + 6'd1;
                if (d_post == 6'd39) d_frz <= 1'b1;
            end
        end
    end
    wire [5:0]  d_i = d_wp - 6'd1 - cpu_adr[9:4];
    wire [31:0] d_rdat = (cpu_adr[3:2] == 2'd0) ? d_w0[d_i] : (cpu_adr[3:2] == 2'd1) ? d_w1[d_i] :
                         (cpu_adr[3:2] == 2'd2) ? d_w2[d_i] : d_w3[d_i];
    always @(posedge clk) t_open_ring <= cpu_asn ? 1'b0 : (t_open_ring | (cpu_ring & ~t_open));
`endif
    always @(posedge clk) begin
        if (!cpu_rst_n || cpu_asn) begin
            t_open  <= 1'b0;
            t_dsack <= 1'b0;
            t_berr  <= 1'b0;
            t_got   <= 1'b0;
            tt_req  <= 1'b0;
            t_rp    <= 3'd0;
        end else begin
            t_rp <= {t_rp[1:0], 1'b0};
            if (t_rp[2]) begin
                t_rd    <= tt_rdata;   // tt_dout loaded on the previous edge: stable now
                t_dsack <= 1'b1;
            end
            if (!t_open & cpu_tt_any & slow_ok) begin   // [F66]
                t_open   <= 1'b1;
                tt_we    <= ~cpu_rwn;
                tt_la    <= cpu_adr[23:2];
                tt_be    <= tt_lo & tt_hi;
                tt_wdata <= cpu_dout;
`ifdef TT_RING
                if (cpu_ring) begin
                    t_rd    <= cpu_adr[23] ? d_rdat : g_rdat; // [STR] $7E800000: stream ring    // DIAG ring readout / arm write: no SDRAM access
                    t_dsack <= 1'b1;
                end else
`endif
                if (cpu_tt_ram) tt_req <= 1'b1;
                else            t_berr <= 1'b1;
            end
            if (tt_req & tt_ack) begin
                tt_req  <= 1'b0;
                t_got   <= 1'b1;
                if (tt_we) t_dsack <= 1'b1;   // posted write
                else       t_rp[0] <= 1'b1;
            end
        end
    end
    wire t_cycle = t_open | cpu_tt_any;   // this 030 cycle is not for the ST side
    reg t_dsack_c = 1'b0, t_berr_c = 1'b0;
    always @(posedge clk_cpu or posedge cpu_asn) begin
        if (cpu_asn) begin
            t_dsack_c <= 1'b0;
            t_berr_c  <= 1'b0;
        end else begin
            t_dsack_c <= t_dsack;
            t_berr_c  <= t_berr;
        end
    end
`endif

    // ---- [F66] translated pins: sample them one clk_cpu after AS ------------------
    // With TC.E = 1 the core's MMU gates AS and drives the address from its ATC lookup in the same clk_cpu
    // as AS (C_ADR -> HITV -> HIT_OK/XLATE -> BLK -> ASn, H_PA -> A31:8). That path is a clk_cpu clock long
    // and did not fit the half clk_cpu (31.25 ns) to the first clk_32 edge with AS low (pmmu8: -7.0 ns,
    // diag builds -13 ns): the bridge could take a half-settled AS/address (logical page, AS glitch) and run
    // an ST cycle with it -> the walker/core got the wrong data (FreeMiNT halted right after pmove tc).
    // While mmu_on, AS/address are sampled only on clk_32 edges that are also clk_cpu rising edges
    // (aligned), i.e. >= 62.5 ns after AS; the live (same-edge) path is off. The SDC gives the paths
    // through the MMU's kept nets (XLATE, HIT_OK, H_PA) two clk_32 cycles. With TC.E = 0 those nets are
    // constant and the bridge timing is exactly the old one.
    reg  ph_cpu = 1'b0;                 // toggles on every clk_cpu rising edge
    always @(posedge clk_cpu) ph_cpu <= ~ph_cpu;
    reg  ph_32 = 1'b0;                  // ph_cpu as seen by the previous clk_32 edge
    always @(posedge clk) ph_32 <= ph_cpu;
    // On a clk_32 edge that is also a clk_cpu rising edge, ph_cpu still has the value it got one clk_cpu
    // earlier, which the clk_32 edge in between already copied: equal. On the edge in between: different.
    wire aligned = (ph_32 == ph_cpu);
    reg  mmu_on = 1'b0;
    always @(posedge clk) mmu_on <= cpu_mmu_on;
    wire slow_ok = ~mmu_on | aligned;   // this clk_32 edge may take a new 030 request

    // ---- front end: request capture (clk_32) -------------------------------
    // clk_cpu is phase-locked to clk_32 (same PLL VCO, every clk_cpu edge is a
    // clk_32 rising edge), so the 030 outputs are sampled directly by clk_32
    // (timed related-clock paths, no synchroniser): the request is seen on
    // the first clk_32 edge after the 030 asserts AS (31.25 ns).
    reg        c_open  = 1'b0;
    reg        c_req_t = 1'b0;
    reg [23:0] c_adr   = 24'd0;
    reg [7:0]  c_adr_hi = 8'd0;   // FalconFPGA DIAG: A31:24 (not used on the ST bus)
    reg [1:0]  c_size  = 2'b00;
    reg        c_rwn   = 1'b1;
    reg [2:0]  c_fc    = 3'd0;
    reg [15:0] c_wdata = 16'd0;

    always @(posedge clk) begin
        if (!cpu_rst_n || cpu_asn) begin
            c_open <= 1'b0;
        end else if (!c_open & slow_ok   // [F66]
`ifdef TTRAM
                     & ~t_cycle
`endif
                     ) begin
            // first clk_32 edge with AS low. Address, SIZE, RW, FC and the
            // write data mux are registered by the 030 with AS (S0).
            c_open  <= 1'b1;
            c_req_t <= ~c_req_t;
            c_adr   <= cpu_adr[23:0];     // A31:24 ignored: 24-bit ST bus
            c_adr_hi <= cpu_adr[31:24];   // FalconFPGA DIAG only
            c_size  <= cpu_size;
            c_rwn   <= cpu_rwn;
            c_fc    <= cpu_fc;
            c_wdata <= cpu_dout[31:16];   // 16-bit port: D31:24 even, D23:16 odd
        end
    end

    // ---- terminations back to the 030 ------------------------------------
    // s_* are clk_32 registers, read by the 030 directly (its DSACK/AVEC/BERR
    // input registers sample on the falling clk_cpu edge = a clk_32 rising
    // edge; timed related-clock paths). The tag stops the 030 from seeing the
    // previous cycle's termination, c_open drops one clk_32 after AS goes high.
    // DSACK for a DTACK-terminated cycle is given early, on the edge where a
    // 68000 samples DTACK (en2 in S4): the 030 samples DSACK on its next
    // falling edge (>= 31.25 ns later) and latches the data one clk_cpu later
    // (>= 156.25 ns after that en2), while s_rdata is written 125 ns after it
    // (S6 en2, the 68000 data latch edge). The s_rdata -> 030 data register
    // path is a timed clk_32 -> clk_cpu_n path (>= 31.25 ns).
    reg        s_tag    = 1'b0;
    reg        s_dsack  = 1'b0;
    reg        s_avec   = 1'b0;
    reg        s_berr   = 1'b0;
    reg [15:0] s_rdata  = 16'hffff;

    wire term_ok = c_open & (s_tag == c_req_t);
`ifdef TTRAM
    // [C8] The ST terminations also go through clk_cpu flops cleared by AS (as the TT ones, C5). The raw
    // clk_32 s_tag/s_dsack -> DSACKn -> core MOVEM_INH_WR -> AR_IN (SP) -> ADR_EFF_I path was a half-cycle
    // (31.25 ns) path failing timing in every build (tt12 -2.6, tt14 -12.7, tt16 -6.0 ns); now a full clk_cpu
    // cycle. DSACK reaches the core's falling-edge sample up to one clk_cpu later; the data is held in
    // s_rdata until the next ST cycle, so the later data latch still sees it.
    reg s_dsack_c = 1'b0, s_avec_c = 1'b0, s_berr_c = 1'b0;
    always @(posedge clk_cpu or posedge cpu_asn) begin
        if (cpu_asn) begin
            s_dsack_c <= 1'b0; s_avec_c <= 1'b0; s_berr_c <= 1'b0;
        end else begin
            s_dsack_c <= term_ok & s_dsack; s_avec_c <= term_ok & s_avec; s_berr_c <= term_ok & s_berr;
        end
    end
    assign cpu_dsackn = t_dsack_c ? 2'b00 : s_dsack_c ? 2'b01 : 2'b11;
    assign cpu_avecn  = ~s_avec_c;
    assign cpu_berrn  = ~(s_berr_c | t_berr_c);
    assign cpu_din    = t_open ? t_rd : {s_rdata, s_rdata};
`else
    assign cpu_dsackn = (term_ok & s_dsack) ? 2'b01 : 2'b11;
    assign cpu_avecn  = ~(term_ok & s_avec);
    assign cpu_berrn  = ~(term_ok & s_berr);
    assign cpu_din    = {s_rdata, s_rdata};
`endif

    // =====================================================================
    // clk_32 domain: the 68000 side
    // =====================================================================
    always @(posedge clk) ipl_r <= {IPL2n, IPL1n, IPL0n};

    (* syn_preserve = 1 *) reg [1:0] rmc_sync = 2'b11;
    (* syn_preserve = 1 *) reg [1:0] rsto_sync = 2'b00;
    (* syn_preserve = 1 *) reg [1:0] hlt_sync = 2'b11;
    always @(posedge clk) begin
        rmc_sync  <= {rmc_sync[0], cpu_rmcn};
        rsto_sync <= {rsto_sync[0], cpu_reset_out};
        hlt_sync  <= {hlt_sync[0], cpu_halt_outn};
    end
    wire req_now  = c_req_t;   // clk_32 register (no synchroniser needed)
    assign dbg_run   = cpu_rst_n;   // FalconFPGA DIAG
    assign dbg_req   = req_now;
    assign dbg_dsack = s_dsack;
    assign dbg_berr  = s_berr;
    assign oRESETn  = ~rsto_sync[1];
    assign oHALTEDn = hlt_sync[1];
    wire rmc_lock = ~rmc_sync[1];

    reg  s_seen = 1'b0;
    // F61: a request is also seen live, on the first clk_32 edge where the
    // 030's AS is low (the edge that opens c_open), straight from the 030's
    // AS/address/SIZE/RW/FC/data outputs (related-clock paths, 31.25 ns). An
    // en1 on that edge starts the ST cycle at once instead of one clk_32
    // later, so the 030 can follow a cycle that ends at S6 with the next S0.
    // q_* are the request fields: live on that edge, captured (c_*) after it.
`ifdef TTRAM
    wire live    = cpu_rst_n & ~cpu_asn & ~c_open & ~t_cycle & ~mmu_on;   // [F66] no live path while translating
`else
    wire live    = cpu_rst_n & ~cpu_asn & ~c_open & ~mmu_on;
`endif
    wire pending = live | (req_now != s_seen);
    wire        q_tag  = live ? ~c_req_t        : c_req_t;
    wire [23:0] q_adr  = live ? cpu_adr[23:0]   : c_adr;
    wire [1:0]  q_size = live ? cpu_size        : c_size;
    wire        q_rwn  = live ? cpu_rwn         : c_rwn;
    wire [2:0]  q_fc   = live ? cpu_fc          : c_fc;
    wire [15:0] q_wdata = live ? cpu_dout[31:16] : c_wdata;
    // request fields are stable: they were written together with the toggle
    // TF534 (Stephen J. Leary), rtl/bus_top.v: CPU space (FC=7) with A19:16=F
    // is an interrupt acknowledge; other CPU-space cycles are not passed on.
    wire req_cpu_space = (q_fc == 3'b111);
    wire req_iack      = req_cpu_space & (q_adr[19:16] == 4'hF);
    wire req_bad_space = req_cpu_space & ~req_iack;

    // ---- input sampling like a 68000 (DTACK/BERR on en2, VPA/BR/BGACK en1)
    // TF534 (Stephen J. Leary), rtl/bus_delay.v: DTACK is delayed (one stage
    // in its ATARI build) before the 030 is terminated; here it is registered.
    reg rDtack = 1'b1, rBerr = 1'b1, Vpai = 1'b1, BRi = 1'b1, BgackI = 1'b1;
    always @(posedge clk) begin
        if (enPhi2) begin
            rDtack <= DTACKn;
            rBerr  <= BERRn;
        end
        if (enPhi1) begin
            Vpai   <= VPAn;
            BRi    <= BRn;
            BgackI <= BGACKn;
        end
    end

    // ---- bus phases (advance on en1): IDLE, S0, S2, S4 (waits), S6 ---------
    localparam [2:0] P_IDLE = 3'd0, P_S0 = 3'd1, P_S2 = 3'd2, P_S4 = 3'd3, P_S6 = 3'd4;
    localparam [1:0] R_DSACK = 2'd0, R_AVEC = 2'd1, R_BERR = 2'd2;

    reg [2:0]  phase  = P_IDLE;
    reg        rAS = 1'b1, rUDS = 1'b1, rLDS = 1'b1, rRWn = 1'b1;
    reg [23:1] r_adr  = 23'h7fffff;
    reg [2:0]  r_fc   = 3'b111;
    reg [15:0] r_dout = 16'hffff;
    reg        r_write = 1'b0, r_uds = 1'b0, r_lds = 1'b0, r_iack = 1'b0, r_tag = 1'b0;
    reg        addr_oe = 1'b0;
    reg        r_ram = 1'b0;     // BRIDGE_EARLY_AS: current cycle is ST RAM
    reg [1:0]  r_res  = R_DSACK;
    reg        iStop  = 1'b0;
    reg [3:0]  eCntr  = 4'd0;
    reg        rVma   = 1'b1;

    // arbitration (68000 style, BG changes on en1, state on en2)
    // TF534 (Stephen J. Leary), rtl/arb.v: BG is only passed to another bus
    // master when the 68000 side is idle (bg_block below).
    localparam [1:0] A_IDLE = 2'd0, A_GRANT = 2'd1, A_BUSY = 2'd2;
    reg [1:0] arb = A_IDLE;
    reg [1:0] arb_nx;
    reg       granting = 1'b0;
    wire bg_block  = (phase == P_S0) | rmc_lock;   // no grant while a cycle starts or during RMC
    // TODO 9: while the 030 holds RMC (rmc_lock) no grant is given (bg_block), so a pending BR must not
    // stop the 030's own cycles either: the WF68K30L asserts RMCn already during the cycles before the TAS
    // read (seen: the move.w d2,(a5) blitter start write and the prefetches after it), and with the blitter
    // requesting (BRi low) the bridge neither started those cycles nor granted the bus -> deadlock (TOS
    // VT52 scroll restart loop tas/nop/bmi at $E06672 hung the machine). A 68000 keeps the bus across RMC.
    wire bus_avail = (BRi | rmc_lock) & BgackI & (arb == A_IDLE);

    always @* begin
        arb_nx = arb;
        case (arb)
        A_IDLE:  if (~BgackI)               arb_nx = A_BUSY;    // taken without BR
                 else if (~BRi & ~bg_block) arb_nx = A_GRANT;
        A_GRANT: if (~BgackI)               arb_nx = A_BUSY;    // master took the bus
                 else if (BRi)              arb_nx = A_IDLE;    // request withdrawn
        A_BUSY:  if (BgackI)                arb_nx = (~BRi & ~bg_block) ? A_GRANT : A_IDLE;
        default:                            arb_nx = A_IDLE;
        endcase
    end
    // BG is asserted in GRANT, and also in BUSY when another master already
    // requests again (68000 behaviour for chained masters)
    wire grant_nx = (arb_nx == A_GRANT) | ((arb_nx == A_BUSY) & ~BRi & ~bg_block);
    wire can_start = pending & ~req_bad_space & bus_avail;   // (CPU space: c_* path above)
    // A23:20 == E is the 256K map. FC/FD/FE is the 192K map.
    wire req_rom = (q_adr[23:20] == 4'hE) |
                   (q_adr[23:16] == 8'hFC) | (q_adr[23:16] == 8'hFD) |
                   (q_adr[23:16] == 8'hFE);


    // UDS/LDS from A0 and SIZE: 16-bit port
    // TF534 (Stephen J. Leary), rtl/bus_top.v: these equations are his.
    wire req_uds = ~q_adr[0];
    wire req_lds =  q_adr[0] | (q_size != 2'b01);

    assign ASn  = rAS;
    assign ASEn = ~(phase == P_S0);
    assign UDSn = rUDS;
    assign LDSn = rLDS;
    assign eRWn = rRWn;
    assign VMAn = rVma;
    assign {FC2, FC1, FC0} = r_fc;
    assign eab  = r_adr;
    assign oEdb = r_dout;

    wire xVma = ~rVma & (eCntr == 4'd8);

    always @(posedge clk) begin
        if (pwrUp) begin
            E     <= 1'b0;
            eCntr <= 4'd0;
            rVma  <= 1'b1;
        end else begin
            // E: 10 en2 periods, 6 low / 4 high (68000 E clock)
            // TF534 (Stephen J. Leary), rtl/m6800.v: 10-state E counter, VMA
            // asserted for VPA cycles and the cycle ended at the E edge.
            if (enPhi2) begin
                if (eCntr == 4'd9)      E <= 1'b0;
                else if (eCntr == 4'd5) E <= 1'b1;
                eCntr <= (eCntr == 4'd9) ? 4'd0 : eCntr + 4'd1;
            end
            if (enPhi2 & addr_oe & ~Vpai & (eCntr == 4'd3))
                rVma <= 1'b0;
            else if (enPhi1 & (eCntr == 4'd0))
                rVma <= 1'b1;
        end
    end

    always @(posedge clk) begin
        if (extReset | pwrUp) begin
            phase   <= P_IDLE;
            rAS     <= 1'b1;
            rUDS    <= 1'b1;
            rLDS    <= 1'b1;
            rRWn    <= 1'b1;
            addr_oe <= 1'b0;
            iStop   <= 1'b0;
            s_seen  <= req_now;
            s_dsack <= 1'b0;
            s_avec  <= 1'b0;
            s_berr  <= 1'b0;
            arb     <= A_IDLE;
            granting <= 1'b0;
            BGn       <= 1'b1;
            rom_fetch <= 1'b0;
        end else begin
            // ---- arbitration: state on en2, BG output on en1 ----
            if (enPhi2) begin
                arb      <= arb_nx;
                granting <= grant_nx;
            end
            if (enPhi1)
                BGn <= ~granting;

            // ---- CPU-space cycles other than IACK: BERR, no ST cycle ----
            if (pending & ~live & req_bad_space) begin   // captured (c_*) request only
                s_seen  <= req_now;
                s_tag   <= req_now;
                s_dsack <= 1'b0;
                s_avec  <= 1'b0;
                s_berr  <= 1'b1;
            end

            // ---- termination sampling like the 68000 ----
            if (enPhi2)
                iStop <= xVma | (Vpai & ~rBerr);

            // early DSACK (see terminations): DTACK seen on the 68000's S4
            // sample edge (en2 in S4, the edge that also loads rDtack)
            // At 16 MHz the 030 would latch the data 94 ns after en2, before
            // S6 en2, so DSACK is given one phase later (S4 -> S6 en1).
            // F61: also at 16 MHz. The read word is taken on the en1 edge
            // that enters S6 (below), 31.25 ns before the 030's data latch
            // edge (>= 93.75 ns after this en2).
            if (enPhi2 & (phase == P_S4) & ~DTACKn) begin
                s_tag   <= r_tag;
                s_dsack <= 1'b1;
            end
            if (enPhi1 & (phase == P_S4) & ~rDtack)
                s_rdata <= iEdb;

            if (enPhi2 & (phase == P_S0))
                addr_oe <= 1'b1;
`ifdef BRIDGE_EARLY_AS
            // F64 BRIDGE_EARLY_AS (busfix/RAM_PATH.md): ST RAM cycles assert AS (and read DS) at the S0 en2,
            // 62.5 ns after the address (68000 8 MHz minimum 30 ns), so an 030 request that lands on an en1
            // still catches its GSTMCU 500 ns slot. Write DS stays 125 ns after AS (S2 en2). Termination
            // (S4/S6) unchanged. Default off = the original 68000 phase timing (AS at S2).
            if (enPhi2 & (phase == P_S0) & r_ram) begin
                rAS <= 1'b0;
                if (r_write) rRWn <= 1'b0;
                else begin rUDS <= ~r_uds; rLDS <= ~r_lds; end
            end
            if (enPhi2 & (phase == P_S2) & r_ram & r_write) begin
                rUDS <= ~r_uds; rLDS <= ~r_lds;
            end
`endif

            // ---- S6 en2: negate AS/DS, latch data, answer the 030 ----
            if (enPhi2 & (phase == P_S6)) begin
                rAS     <= 1'b1;
                rUDS    <= 1'b1;
                rLDS    <= 1'b1;
                if (r_res != R_DSACK | rDtack)   // VPA/E cycle, IACK vector, BERR
                    s_rdata <= iEdb;
                s_tag   <= r_tag;
                s_dsack <= (r_res == R_DSACK);
                s_avec  <= (r_res == R_AVEC);
                s_berr  <= (r_res == R_BERR);
            end

            if (enPhi1) begin
                case (phase)
                P_S0: begin
                    phase <= P_S2;
                    rAS   <= 1'b0;
                    if (r_write) rRWn <= 1'b0;
                    else begin
                        rUDS <= ~r_uds;
                        rLDS <= ~r_lds;
                    end
                end
                P_S2: begin
                    phase <= P_S4;
                    if (r_write) begin
                        rUDS <= ~r_uds;
                        rLDS <= ~r_lds;
                    end
                end
                P_S4: begin
                    if (~rDtack | iStop) begin
                        phase <= P_S6;
                        if (~rDtack)    r_res <= R_DSACK;
                        else if (~rVma) r_res <= r_iack ? R_AVEC : R_DSACK; // VPA/E cycle (terminated at S6)
                        else            r_res <= R_BERR;
                    end
                end
                default: ;   // P_IDLE / P_S6 handled below
                endcase

                if (phase == P_S6) begin
                    rRWn    <= 1'b1;
                    addr_oe <= 1'b0;
                    phase   <= P_IDLE;
                end

                if ((phase == P_IDLE | phase == P_S6) & can_start) begin
                    if (req_rom) rom_fetch <= 1'b1;
                    // accept the 030 request: 68000 S0
                    phase   <= P_S0;
                    s_seen  <= q_tag;
                    s_dsack <= 1'b0;
                    s_avec  <= 1'b0;
                    s_berr  <= 1'b0;
                    r_tag   <= q_tag;
                    r_adr   <= q_adr[23:1];
                    r_fc    <= q_fc;
                    r_write <= ~q_rwn;
                    r_dout  <= q_wdata;
                    r_uds   <= req_uds;
                    r_lds   <= req_lds;
                    r_iack  <= req_iack;
                    r_ram   <= ~req_cpu_space & (q_adr[23:22] == 2'b00);
                end
            end
        end
    end

    // ---- FalconFPGA DIAG diag030b: first-BERR latch (clk_32) ----
    // Observation only. The 030 waits for its termination, so c_* still hold
    // the faulting request when s_berr is set (both BERR paths).
    wire d_berr_now = (pending & req_bad_space) |
                      (enPhi2 & (phase == P_S6) & (r_res == R_BERR));
    reg        d_got   = 1'b0;
    reg [6:0]  d_info  = 7'd0;    // FC2:0, RW, SIZE1:0, bad_space
    reg [31:0] d_badr  = 32'd0;
    always @(posedge clk) begin
        if (extReset | pwrUp) begin
            d_got  <= 1'b0;
            d_info <= 7'd0;
            d_badr <= 32'd0;
        end else if (d_berr_now & ~d_got) begin
            d_got  <= 1'b1;
            d_info <= {c_fc, c_rwn, c_size, req_bad_space};
            d_badr <= {c_adr_hi, c_adr};
`ifdef TTRAM
        end else if (t_berr & ~d_got) begin
            // TT front-end BERR (A31:24 not $00/$01/$FF, or beyond TT_BYTES): 030 pins, bad_space bit = 1
            d_got  <= 1'b1;
            d_info <= {cpu_fc, cpu_rwn, cpu_size, 1'b1};
            d_badr <= cpu_adr;
`endif
        end
    end

    // ---- FalconFPGA DIAG diag030c: 030 bus-cycle watch (clk_32 since F58) ----
    // Taken straight from the WF68K30L outputs (cpu_adr/cpu_fc/...), on the
    // same clk_cpu edge where the front end opens a request (c_open 0->1),
    // independent of c_adr (diag030b's PC rows read A20:18 as 0).
    wire x_start = cpu_rst_n & ~cpu_asn & ~c_open;
    wire x_term  = ~cpu_asn & ((cpu_dsackn != 2'b11) | ~cpu_berrn | ~cpu_avecn);
    reg [31:0] x_adr   = 32'd0;   // last started cycle A31:0
    reg [2:0]  x_fc    = 3'd0;
    reg        x_rwn   = 1'b1;
    reg [1:0]  x_size  = 2'b00;
    reg        x_done  = 1'b1;    // last started cycle has been terminated
    reg        x_hung  = 1'b0;    // sticky: one cycle open > 2^13 clk_cpu (~1 ms)
    reg [15:0] x_tmr   = 16'd0;   // F58: clk_32 (2^15 = ~1 ms)
    reg [2:0]  x_tres  = 3'd0;    // last termination {DSACK, BERR, AVEC}
    reg        x_iack_s = 1'b0, x_iack_d = 1'b0, x_cpusp = 1'b0, x_iack_av = 1'b0;
    reg [23:0] x_pc    = 24'd0;   // live last program fetch A23:0
    reg [7:0]  x_cnt   = 8'd0;    // bus cycles started (mod 256)
    wire       x_iack_now = (cpu_fc == 3'b111) & (cpu_adr[19:16] == 4'hF);
    always @(posedge clk) begin
        if (!cpu_rst_n) begin
            x_adr <= 32'd0;  x_fc <= 3'd0;  x_rwn <= 1'b1;  x_size <= 2'b00;
            x_done <= 1'b1;  x_hung <= 1'b0;  x_tmr <= 16'd0;  x_tres <= 3'd0;
            x_iack_s <= 1'b0;  x_iack_d <= 1'b0;  x_cpusp <= 1'b0;  x_iack_av <= 1'b0;
            x_pc <= 24'd0;  x_cnt <= 8'd0;
        end else begin
            if (x_start) begin
                x_adr  <= cpu_adr;
                x_fc   <= cpu_fc;
                x_rwn  <= cpu_rwn;
                x_size <= cpu_size;
                x_done <= 1'b0;
                x_tmr  <= 14'd0;
                x_cnt  <= x_cnt + 8'd1;
                if (cpu_fc[1:0] == 2'b10) x_pc <= cpu_adr[23:0];
                if (cpu_fc == 3'b111) x_cpusp <= 1'b1;
                if (x_iack_now) x_iack_s <= 1'b1;
            end else if (!x_done) begin
                if (x_term) begin
                    x_done <= 1'b1;
                    x_tres <= {(cpu_dsackn != 2'b11), ~cpu_berrn, ~cpu_avecn};
                    if ((x_fc == 3'b111) & (x_adr[19:16] == 4'hF)) begin
                        x_iack_d <= 1'b1;
                        if (~cpu_avecn) x_iack_av <= 1'b1;
                    end
                end else if (~x_tmr[15])
                    x_tmr <= x_tmr + 16'd1;
                else
                    x_hung <= 1'b1;
            end
        end
    end
    wire x_inprog = ~x_done & ~cpu_asn;
    wire [31:0] row_d = {
        x_fc, x_rwn,                                  // G1
        x_size, x_inprog, x_hung,                     // G2
        x_tres, 1'b0,                                 // G3 DSACK BERR AVEC -
        x_iack_s, x_iack_d, x_cpusp, x_iack_av,       // G4
        cpu_halt_outn, cpu_reset_out, cpu_rst_n, cpu_ipendn,   // G5
        cpu_statusn, ipl_r,                           // G6 STATUSn IPL2n:0n
        cpu_asn, cpu_dsn, cpu_dsackn,                 // G7 ASn DSn DSACK1n DSACK0n
        cpu_berrn, cpu_avecn, cpu_rmcn, cpu_rwn       // G8
    };
    wire [31:0] row_e = {
        phase, pending,                               // G1
        req_now, s_seen, c_open, term_ok,             // G2
        rAS, rUDS, rLDS, rRWn,                        // G3
        rDtack, rBerr, Vpai, iStop,                   // G4
        s_dsack, s_avec, s_berr, s_tag,               // G5
        r_tag, addr_oe, rVma, r_iack,                 // G6
        arb, BGn, can_start,                          // G7
        r_res, BRi, BgackI                            // G8
    };
`ifdef DIAG_EXCWATCH
    // ---- FalconFPGA DIAG excwatch (float panic). Observation only.
    // The core reports every exception it takes (DBG_EXC strobe = handler address load) with the
    // vector number, the stacked SR, the stacked PC, A5 and BIW_0 (opcode word in the decoder).
    // The last 16 are kept; armed by the first user-mode cycle, frozen by a bus/address error
    // (vector 2/3) whose stacked PC is outside RAM and ROM ($400000-$DFFFFF), i.e. the EmuTOS panic.
    // V2: the last 8 code fetches {A23:0, D15:0} (data as delivered to the core) are frozen by the
    // first vector 6 (CHK) after arming, and CPU accesses to the word at EW_SNOOP ($055D18) are snooped:
    // last write data, last data read, last code fetch data, write/fetch counts (saturating at 15).
    // One page per ~0.13 s; rows c..f = {frz, page3:0, 1, exceptions seen mod 64 (6),
    //   entry[page] {vector 8, SR 16, PC 23:0, BIW_0 16, 8'b0}, 44 bits:
    //   page 0-7: {f_frz, 3'b0, fetch[page] A23:0 D15:0} (0 = newest), page 8-15: snoop
    //   {last write data 16, last fetch data 16, write count 4, fetch count 4, 3'b0, f_frz}} on page 8,
    //   pages 9-15: V3 program-fetch jumps j[page-9] {from A21:0, to A21:0} (0 = newest), frozen with fetches.
    localparam [23:0] EW_SNOOP = 24'h055D18;
    reg        e_arm = 1'b0, e_frz = 1'b0, f_frz = 1'b0;
    reg [71:0] e_h [0:15];
    reg [39:0] f_h [0:7];
    reg [5:0]  e_cnt = 6'd0;
    reg [24:0] e_tmr = 25'd0;
    reg [15:0] s_wd = 16'd0, s_fd = 16'd0, s_rd = 16'd0, e_wd = 16'd0;
    reg        e_wds = 1'b0;
    reg [3:0]  s_wn = 4'd0, s_fn = 4'd0;
    reg [43:0] j_h [0:6];               // V3: last 7 program-fetch discontinuities {from A21:0, to A21:0}
    reg [23:0] j_last = 24'd0;
    integer    ei;
    reg        e_stb_d = 1'b0;          // clk_cpu strobe seen in clk_32: use its rising edge
    wire       e_stb = cpu_dbg_exc[104] & ~e_stb_d;
    wire [7:0] e_vec = cpu_dbg_exc[103:96];
    wire [23:0] e_pc = cpu_dbg_exc[71:48];
    wire       e_bad = (e_vec == 8'd2 || e_vec == 8'd3) &&
                       ((e_pc[23] ^ e_pc[22]) | (e_pc[23] & e_pc[22] & ~e_pc[21]));
    wire       e_cyc = !x_done & x_term;             // a cycle terminates (as the hiwatch history)
    wire       e_cod = x_fc[1:0] == 2'b10;           // program space
    wire       e_hit = x_adr[23:1] == EW_SNOOP[23:1] && x_fc != 3'b111;
    always @(posedge clk) begin
        e_tmr <= e_tmr + 25'd1;
        e_stb_d <= cpu_dbg_exc[104];
        if (x_start) e_wds <= 1'b0;
        else if (!x_done & ~cpu_dsn & ~e_wds) begin e_wds <= 1'b1; e_wd <= cpu_dout[31:16]; end
        if (extReset | pwrUp) begin
            e_arm <= 1'b0;  e_frz <= 1'b0;  f_frz <= 1'b0;  e_cnt <= 6'd0;  s_wn <= 4'd0;  s_fn <= 4'd0;
        end else if (!e_frz) begin
            if (x_start & ~cpu_fc[2]) e_arm <= 1'b1;
            if (e_arm & e_stb) begin
                for (ei = 15; ei > 0; ei = ei - 1) e_h[ei] <= e_h[ei-1];
                e_h[0] <= {e_vec, cpu_dbg_exc[95:80], e_pc, cpu_dbg_exc[15:0], 8'd0};
                e_cnt  <= e_cnt + 6'd1;
                if (e_bad) e_frz <= 1'b1;
                if (e_vec == 8'd6) f_frz <= 1'b1;
            end
            if (e_cyc & ~f_frz & e_cod & x_rwn) begin
                for (ei = 7; ei > 0; ei = ei - 1) f_h[ei] <= f_h[ei-1];
                f_h[0] <= {x_adr[23:0], cpu_din[31:16]};
                j_last <= x_adr[23:0];
                if (x_adr[23:0] != j_last && x_adr[23:0] != j_last + 24'd2) begin
                    for (ei = 6; ei > 0; ei = ei - 1) j_h[ei] <= j_h[ei-1];
                    j_h[0] <= {j_last[21:0], x_adr[21:0]};
                end
            end
            if (e_cyc & e_hit & ~f_frz) begin
                if (!x_rwn) begin s_wd <= e_wds ? e_wd : cpu_dout[31:16]; if (s_wn != 4'hF) s_wn <= s_wn + 4'd1; end
                else if (e_cod) begin s_fd <= cpu_din[31:16]; if (s_fn != 4'hF) s_fn <= s_fn + 4'd1; end
                else s_rd <= cpu_din[31:16];
            end
        end
    end
`ifdef DIAG_GDTRACE
    // V5 GEMDOS trace: for every TRAP #1 (vector 33) the stacked PC and the first 5 user-data (FC1) read words
    // after it (EmuTOS reads the function number and the arguments from the caller's stack). Last 16 complete calls,
    // frozen at the first vector 6. Entry (116) = {PC 23:0, w0 (function), w1, w2, w3, w4, 12'b0}.
    reg [115:0] g_h [0:15];
    reg [115:0] g_e;
    reg [2:0]   g_k = 3'd5;
    reg [5:0]   g_n = 6'd0;
    integer     gi;
    always @(posedge clk) begin
        if (extReset | pwrUp) begin g_k <= 3'd5; g_n <= 6'd0; end
        else if (!f_frz & e_arm) begin
            if (e_stb & (e_vec == 8'd33) & ~cpu_dbg_exc[93]) begin   // from user mode (stacked SR S=0)
                g_e <= {e_pc, 92'd0};  g_k <= 3'd0;
                if (g_n != 6'd63) g_n <= g_n + 6'd1;
            end else if (e_cyc & x_rwn & (x_fc == 3'b001) & (g_k != 3'd5)) begin
                case (g_k)
                    3'd0: g_e[91:76] <= cpu_din[31:16];
                    3'd1: g_e[75:60] <= cpu_din[31:16];
                    3'd2: g_e[59:44] <= cpu_din[31:16];
                    3'd3: g_e[43:28] <= cpu_din[31:16];
                    default: g_e[27:12] <= cpu_din[31:16];
                endcase
                if (g_k == 3'd4) begin
                    for (gi = 15; gi > 0; gi = gi - 1) g_h[gi] <= g_h[gi-1];
                    g_h[0] <= {g_e[115:28], cpu_din[31:16], 12'd0};
                end
                g_k <= g_k + 3'd1;
            end
        end
    end
    wire [3:0] e_pg = e_tmr[24:21];
    assign dbg_trace = {d_got, d_info, d_badr, e_frz, e_pg, f_frz, g_n, g_h[e_pg]};
`elsif DIAG_WRWATCH
    // V4 write-watch: CPU writes into $55C96-$55D21 (any FC but IACK). Entry (116) =
    // {PC 23:0 (core PC at the cycle start = the writing instruction, for BSR/JSR pushes already the target),
    //  A23:0, D15:0 (data at DS), SIZ1:0, FC2:0, SR 15:0, A5 23:0, 3'b0}. Slots 0-7 = FIRST 8 writes after
    // arming, 8-15 = LAST 8 (15 = newest), all frozen by the first vector 6. w_n = total (saturates at 63).
    // Only the 030 is visible here: DMA/shifter/blitter/helper RAM writes do not pass the bridge.
    reg [115:0] w_h [0:15];
    reg [5:0]   w_n = 6'd0;
    reg         w_pend = 1'b0;
    reg [115:0] w_e;
    integer     wi;
    wire        w_hit = (x_adr[23:0] >= 24'h055C96) && (x_adr[23:0] <= 24'h055D21) && (x_fc != 3'b111);
    always @(posedge clk) begin
        if (extReset | pwrUp) begin w_n <= 6'd0; w_pend <= 1'b0; end
        else if (!f_frz & e_arm) begin
            if (x_start) w_e <= {cpu_dbg_exc[71:48], 92'd0};          // PC at the start of the cycle
            if (e_cyc & ~x_rwn & w_hit) begin
                if (w_n < 6'd8) w_h[w_n[2:0]] <= {w_e[115:92], x_adr[23:0], e_wds ? e_wd : cpu_dout[31:16],
                                                  x_size, x_fc, cpu_dbg_exc[95:80], cpu_dbg_exc[39:16], 3'd0};
                else begin
                    for (wi = 8; wi < 15; wi = wi + 1) w_h[wi] <= w_h[wi+1];
