`else
    wire [3:0] e_pg = e_tmr[24:21];
    wire [43:0] e_x = (e_pg == 4'd8) ? {s_wd, s_fd, s_wn, s_fn, 3'd0, f_frz} :
                      e_pg[3] ? j_h[e_pg[2:0] - 3'd1] : {f_frz, 3'd0, f_h[e_pg[2:0]]};
