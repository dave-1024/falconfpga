#!/usr/bin/env python3
# [F1] Generates prog_movemx.s: MOVEM over many register masks (empty, full, every single register,
# odd/even counts, first/last-only, random), both sizes, every memory-to-register and register-to-memory
# addressing mode, the base register in and out of the list, and bus errors in the middle of a MOVEM
# (reads and writes). After every case all registers are stored, so cmp_wr.sh compares the old and the
# new core write for write. Usage: gen_movemx.py [seed] > prog_movemx.s
import random, sys
R = random.Random(int(sys.argv[1]) if len(sys.argv) > 1 else 1)
REGS = ['d%d' % i for i in range(8)] + ['a%d' % i for i in range(8)]
def rlist(mask, predec):
    # normal: bit0 = d0 .. bit15 = a7; -(An): bit0 = a7 .. bit15 = d0
    regs = [REGS[15 - i] if predec else REGS[i] for i in range(16) if mask >> i & 1]
    return '/'.join(regs) if regs else '#0'  # empty list
masks = [0x0000, 0xFFFF, 0x0001, 0x8000, 0x8001, 0x0180, 0x0081, 0x7FFE, 0x5555, 0xAAAA, 0x00FF, 0xFF00, 0x0F0F]
masks += [1 << i for i in range(16)]
while len(masks) < 44:
    m = R.getrandbits(16)
    if m: masks.append(m)
masks = list(dict.fromkeys(masks))
o = []; e = o.append
e('| generated by gen_movemx.py: do not edit'); e('        .text'); e('        .org 0')
e('        .long   0x00008000'); e('        .long   0x00fc0008')
e('start:  move.l  #berr,0x08'); e('        clr.l   0x3000'); e('        move.l  sp,0x3008')
n = 0
def case(code, base, mask, predec, pre=()):
    global n; n += 1
    e('| case %d' % n)
    e('        movem.l init,d0-d7/a0-a6')
    if base is not None: e('        lea     0x%x.l,a%d' % (base[1], base[0]))
    for p in pre: e('        ' + p)
    e('        move.l  #r%d,0x3004' % n)
    e('        ' + code)
    e('r%d:     movem.l d0-d7/a0-a6,0x5000' % n)
masks_mr = [m & 0x7FFF for m in masks]  # no A7 for memory-to-register (keeps the stack)
for sz in 'wl':
    for i, m in enumerate(masks):
        a = (i % 7); lst = rlist(m, False); lstp = rlist(m, True)
        mr = rlist(masks_mr[i], False)
        # register to memory
        for code, base in (('movem.%s %%s,(a%d)' % (sz, a), (a, 0x7000)),
                           ('movem.%s %%s,-(a%d)' % (sz, a), (a, 0x7100)),
                           ('movem.%s %%s,0x20(a%d)' % (sz, a), (a, 0x7200)),
                           ('movem.%s %%s,(-6,a%d,d7.w)' % (sz, a), (a, 0x7300)),
                           ('movem.%s %%s,0x7400.w' % sz, None),
                           ('movem.%s %%s,0x7500.l' % sz, None)):
            l = lstp if '-(a' in code else lst
            if l is None: continue
            case(code % l, base, m, '-(a' in code)
        if mr is None: continue
        # memory to register
        for code, base in (('movem.%s (a%d),%%s' % (sz, a), (a, 0x6000)),
                           ('movem.%s (a%d)+,%%s' % (sz, a), (a, 0x6010)),
                           ('movem.%s 0x22(a%d),%%s' % (sz, a), (a, 0x6000)),
                           ('movem.%s (6,a%d,d7.w),%%s' % (sz, a), (a, 0x6000)),
                           ('movem.%s 0x6040.w,%%s' % sz, None),
                           ('movem.%s 0x6080.l,%%s' % sz, None),
                           ('movem.%s init(pc),%%s' % sz, None)):
            case(code % mr, base, masks_mr[i], False)
# every single register (base register included) and base + one other register, -(An) and (An)+
for sz in 'wl':
    for a in range(7):
        for r in range(16):
            case('movem.%s %s,-(a%d)' % (sz, REGS[r], a), (a, 0x7100), 0, True)
            if r != 15:
                case('movem.%s (a%d)+,%s' % (sz, a, REGS[r]), (a, 0x6010), 0, False)
            if REGS[r] != 'a%d' % a and r != 15:
                case('movem.%s %s/a%d,-(a%d)' % (sz, REGS[r], a, a), (a, 0x7100), 0, True)
                case('movem.%s (a%d)+,%s/a%d' % (sz, a, REGS[r], a), (a, 0x6010), 0, False)
                case('movem.%s (a%d),%s/a%d' % (sz, a, REGS[r], a), (a, 0x6010), 0, False)
# bus errors in the middle of a MOVEM
for sz, st in (('l', 4), ('w', 2)):
    for k in (0, 1, 2, 5):
        # reads: the (k+1)th register access ends with BERR ($3504 = faulting RAM word)
        case('movem.%s (a2),d0-d6/a3-a5' % sz, (2, 0x6000), 0, False,
             ('move.w  #0x%x,0x3504' % (0x6000 + k * st),))
        case('movem.%s (a2)+,d1/d3/d5/a2/a4' % sz, (2, 0x6000), 0, False,
             ('move.w  #0x%x,0x3504' % (0x6000 + k * st),))
        e('        clr.w   0x3504')
        # writes: crossing into the unmapped range at $10000
        case('movem.%s d0-d7/a0-a6,(a1)' % sz, (1, 0x10000 - (k + 1) * st), 0, False)
        case('movem.%s d1/d2/d4/a3,0x%x.l' % (sz, 0x10000 - k * st if k else 0xFFFE), None, 0, False)
        # reads crossing into the unmapped range
        case('movem.%s (a0)+,d1-d6/a1-a3' % sz, (0, 0x10000 - (k + 1) * st), 0, False)
e('        move.l  0x3000,0x5100')
e('        move.l  #0x600dc0de,0x3300')
e('9:      bra.s   9b')
e('berr:   addq.l  #1,0x3000')
e('        move.w  (sp),0x5200'); e('        move.l  2(sp),0x5202'); e('        move.w  6(sp),0x5206')
e('        move.w  0xa(sp),0x5208'); e('        move.l  0x10(sp),0x520a')
e('        clr.w   0x3504')
e('        movea.l 0x3008,sp'); e('        move.l  0x3004,-(sp)'); e('        rts')
e('        .even')
e('init:   .long   0x11110001,0x22220002,0x33330003,0x44440004,0x55550005,0x66660006,0x77770007,0x00000008')
e('        .long   0xa0a0a0a0,0xa1a1a1a1,0xa2a2a2a2,0xa3a3a3a3,0xa4a4a4a4,0xa5a5a5a5,0xa6a6a6a6')
e('        .long   0x01020304,0x05060708,0x090a0b0c,0x0d0e0f10,0x8899aabb,0xccddeeff,0x7f7f8080,0xfedcba98')
print('\n'.join(o))
sys.stderr.write('%d cases\n' % n)
